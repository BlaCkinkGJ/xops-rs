//! The one way the game reaches a file.
//!
//! The desktop reads the file system. The web has none, so a browser build fetches its
//! data from the page's own origin instead: the data is served beside the page, and it
//! is all read into memory before the game starts. Every caller goes through here so that
//! both builds share one set of call sites and one set of error kinds, which is what lets
//! the loaders match on `NotFound` and stay unchanged.

use std::io;
use std::path::Path;

/// Reads a whole file.
///
/// The desktop reads the file system. The web has none, so it asks the page's own origin
/// for the path, which is what a browser build means: the data is served beside the page.
pub fn read_file(path: impl AsRef<Path>) -> io::Result<Vec<u8>> {
	let path = path.as_ref();

	#[cfg(not(target_arch = "wasm32"))]
	{
		std::fs::read(path)
	}

	#[cfg(target_arch = "wasm32")]
	{
		web::read(path)
	}
}

/// Writes a whole file. The configuration file is the only caller.
pub fn write_file(path: impl AsRef<Path>, data: &[u8]) -> io::Result<()> {
	let path = path.as_ref();

	#[cfg(not(target_arch = "wasm32"))]
	{
		std::fs::write(path, data)
	}

	#[cfg(target_arch = "wasm32")]
	{
		web::write(path, data)
	}
}

/// Whether a path exists.
pub fn exists(path: impl AsRef<Path>) -> bool {
	let path = path.as_ref();

	#[cfg(not(target_arch = "wasm32"))]
	{
		path.exists()
	}

	#[cfg(target_arch = "wasm32")]
	{
		web::exists(path)
	}
}

/// The names of the entries in a directory, which is what the case-insensitive path
/// resolution walks. A file system gives them directly. The web has no directories, so
/// the browser build names them from the manifest the packaging step writes, which the
/// preload pass has read into memory.
pub fn read_dir_names(path: impl AsRef<Path>) -> io::Result<Vec<String>> {
	let path = path.as_ref();

	#[cfg(not(target_arch = "wasm32"))]
	{
		let mut names = Vec::new();
		for entry in std::fs::read_dir(path)? {
			names.push(entry?.file_name().to_string_lossy().into_owned());
		}
		Ok(names)
	}

	#[cfg(target_arch = "wasm32")]
	{
		web::read_dir_names(path)
	}
}

/// Fetches the whole data directory into memory, before the game starts.
///
/// A browser will not let a synchronous request read binary, and every loader in the game
/// is synchronous, so the bytes have to be here before the first one runs. The page's
/// entry point calls this once, and everything after it is answered from memory. The set
/// of files is the manifest `scripts/index_data.py` writes, which is also what a directory
/// listing comes from.
///
/// Fails with the reason when the manifest or one of the files could not be fetched.
#[cfg(target_arch = "wasm32")]
pub async fn preload() -> Result<(), String> {
	web::preload().await
}

/// The browser side, where a path is a URL under the page's own origin.
///
/// There are no requests after startup: the whole data directory is fetched in one pass
/// and the accessors below answer from the map it built.
#[cfg(target_arch = "wasm32")]
mod web {
	use std::collections::HashMap;
	use std::io;
	use std::path::Path;
	use std::sync::OnceLock;

	use wasm_bindgen::{JsCast, JsValue};
	use wasm_bindgen_futures::JsFuture;
	use web_sys::Response;

	/// The manifest directory listings are read from, generated by `scripts/index_data.py`.
	const INDEX: &str = "data/index.json";

	/// Every preloaded file, keyed by the path it was fetched from.
	static FILES: OnceLock<HashMap<String, Vec<u8>>> = OnceLock::new();

	/// The URL the page serves `path` at. A path that is not UTF-8 is taken lossily,
	/// which is all a URL can carry, matching what the rest of the port does with a path.
	fn url(path: &Path) -> String {
		String::from_utf8_lossy(path.as_os_str().as_encoded_bytes()).replace('\\', "/")
	}

	/// A message a failed promise turned into, so a failure names what it was doing.
	fn js_message(context: &str, value: &JsValue) -> String {
		let message = value.as_string().unwrap_or_else(|| format!("{value:?}"));
		format!("{context}: {message}")
	}

	pub async fn preload() -> Result<(), String> {
		let window = web_sys::window().ok_or("no window")?;

		let response = JsFuture::from(window.fetch_with_str(INDEX))
			.await
			.map_err(|e| js_message("fetch the index", &e))?;
		let response: Response = response.unchecked_into();
		if !response.ok() {
			return Err(format!("HTTP {} for {INDEX}", response.status()));
		}
		let text = JsFuture::from(
			response
				.text()
				.map_err(|e| js_message("read the index", &e))?,
		)
		.await
		.map_err(|e| js_message("read the index", &e))?;
		let paths = parse_list(&text.as_string().ok_or("the index is not text")?)?;

		// Every request is made before any is awaited, so the fetches run at once instead
		// of a round trip at a time.
		let requests = js_sys::Array::new();
		for path in &paths {
			requests.push(&window.fetch_with_str(path));
		}
		let responses = JsFuture::from(js_sys::Promise::all(&requests))
			.await
			.map_err(|e| js_message("fetch the data", &e))?;
		let responses: js_sys::Array = responses.unchecked_into();

		let bodies = js_sys::Array::new();
		for index in 0..responses.length() {
			let response: Response = responses.get(index).unchecked_into();
			if !response.ok() {
				return Err(format!(
					"HTTP {} for {}",
					response.status(),
					paths[index as usize]
				));
			}
			let body = response
				.array_buffer()
				.map_err(|e| js_message("read a body", &e))?;
			bodies.push(&JsValue::from(body));
		}
		let bodies = JsFuture::from(js_sys::Promise::all(&bodies))
			.await
			.map_err(|e| js_message("read the bodies", &e))?;
		let bodies: js_sys::Array = bodies.unchecked_into();

		let mut files = HashMap::with_capacity(paths.len());
		for (index, path) in paths.iter().enumerate() {
			let bytes = js_sys::Uint8Array::new(&bodies.get(index as u32)).to_vec();
			files.insert(path.clone(), bytes);
		}
		FILES.set(files).map_err(|_| "the data was already loaded".to_string())?;
		Ok(())
	}

	/// The bytes of a preloaded file, or `NotFound` when it was not among them.
	pub fn read(path: &Path) -> io::Result<Vec<u8>> {
		let url = url(path);
		FILES
			.get()
			.and_then(|files| files.get(&url))
			.cloned()
			.ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, format!("{url} is not loaded")))
	}

	/// A page cannot write to the server that served it, so this always fails. The
	/// configuration file is the only caller and a browser build cannot save it.
	pub fn write(_path: &Path, _data: &[u8]) -> io::Result<()> {
		Err(io::Error::new(
			io::ErrorKind::Unsupported,
			"a page cannot write to the server that served it",
		))
	}

	pub fn exists(path: &Path) -> bool {
		FILES
			.get()
			.is_some_and(|files| files.contains_key(&url(path)))
	}

	pub fn read_dir_names(path: &Path) -> io::Result<Vec<String>> {
		let key = url(path);
		let key = key.trim_start_matches("./").trim_end_matches('/');
		let key = if key == "." { "" } else { key };
		let prefix = format!("{key}/");

		let files = FILES.get().ok_or_else(|| {
			io::Error::new(io::ErrorKind::NotFound, "the data has not been loaded")
		})?;
		let mut names = Vec::new();
		for entry in files.keys() {
			let rest = if key.is_empty() {
				entry.as_str()
			} else if let Some(rest) = entry.strip_prefix(&prefix) {
				rest
			} else {
				continue;
			};
			let child = rest.split('/').next().unwrap_or("");
			if !child.is_empty() && !names.iter().any(|name| name == child) {
				names.push(child.to_string());
			}
		}
		Ok(names)
	}

	/// The strings of the JSON array the packaging step wrote.
	fn parse_list(text: &str) -> Result<Vec<String>, String> {
		let value = js_sys::JSON::parse(text).map_err(|e| js_message("parse the index", &e))?;
		let array: js_sys::Array = value.unchecked_into();
		let mut entries = Vec::with_capacity(array.length() as usize);
		for index in 0..array.length() {
			if let Some(entry) = array.get(index).as_string() {
				entries.push(entry);
			}
		}
		Ok(entries)
	}
}
